import 'reflect-metadata';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { Controller, Get, Inject, Req, UseGuards } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import { WebSocketServer } from 'ws';
const fixtures = JSON.parse(readFileSync(new URL('./fixtures/canonical-worker.json', import.meta.url), 'utf8'));
const envelope = fixture => `{"defs":${fixture.defs},"timestamp":${fixture.timestamp},"signature":${JSON.stringify(fixture.signature)},"kid":${JSON.stringify(fixture.kid)}}`;
const listen = server => new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
const stop = server => new Promise(resolve => server.close(resolve));
async function eventually(assertion) {
  const deadline = Date.now() + 4000;
  while (true) { try { await assertion(); return; } catch (error) { if (Date.now() >= deadline) throw error; await new Promise(resolve => setTimeout(resolve, 20)); } }
}
// Shared behavioral contract runs once against source and again in an isolated
// installed-tarball consumer. The fixtures are public Worker-format signatures,
// not generated by or coupled to the Node SDK verification implementation.
export async function verifyCanonicalBoundary({ TogglyModule, TogglyProvider, TogglyService, FeatureFlag, FeatureFlagGuard }) {
  for (const fixture of Object.values(fixtures)) {
    const key = await webcrypto.subtle.importKey('jwk', fixture.jwks.keys[0], { name: 'ECDSA', namedCurve: 'P-256' }, false, ['verify']);
    const digest = await webcrypto.subtle.digest('SHA-256', new TextEncoder().encode(`${fixture.defs}|${fixture.timestamp}`));
    assert.equal(await webcrypto.subtle.verify({ name: 'ECDSA', hash: 'SHA-256' }, key, Buffer.from(fixture.signature, 'base64'), digest), true);
  }
  const state = { body: envelope(fixtures.initial), jwks: fixtures.initial.jwks, jwksRequests: 0 };
  const transport = createServer((req, res) => {
    res.setHeader('content-type', 'application/json');
    if (req.url.startsWith('/.well-known/jwks')) { state.jwksRequests++; res.end(JSON.stringify(state.jwks)); }
    else res.end(state.body);
  });
  const socketServer = createServer();
  const wss = new WebSocketServer({ server: socketServer });
  let app;
  try {
    await listen(transport); await listen(socketServer);
    const connection = new Promise(resolve => wss.once('connection', resolve));
    class SignedController {
      constructor(toggly) { this.toggly = toggly; }
      async evaluate(req) {
        const entity = { kind: 'Order', key: req.query.user, attributes: { Vip: req.query.user === 'alice' } };
        return { context: await this.toggly.context(), flags: await Promise.all(['target', 'claims', 'country', 'groups', 'vip'].map(key => this.toggly.isFeatureOn(key, { entity }))) };
      }
      guarded() { return { allowed: true }; }
    }
    Controller()(SignedController);
    Inject(TogglyService)(SignedController, undefined, 0);
    const evaluation = Object.getOwnPropertyDescriptor(SignedController.prototype, 'evaluate');
    Get('evaluate')(SignedController.prototype, 'evaluate', evaluation);
    Req()(SignedController.prototype, 'evaluate', 0);
    const gated = Object.getOwnPropertyDescriptor(SignedController.prototype, 'guarded');
    Get('guarded')(SignedController.prototype, 'guarded', gated);
    UseGuards(FeatureFlagGuard)(SignedController.prototype, 'guarded', gated);
    FeatureFlag('target')(SignedController.prototype, 'guarded', gated);
    let contextCalls = 0;
    const errors = [];
    const mod = await Test.createTestingModule({
      imports: [TogglyModule.forRoot({
        appKey: 'loopback-contract', baseUrl: `http://127.0.0.1:${transport.address().port}`,
        streamingUrl: `ws://127.0.0.1:${socketServer.address().port}`, verifySignatures: true,
        allowedKeyIds: [fixtures.initial.kid, fixtures.rotated.kid], enableStreaming: true,
        registerContextsOnStartup: false, enableUsageTracking: false, enableMetrics: false, refreshInterval: 0,
        onError: error => { errors.push(error); },
        contextFactory: req => { contextCalls++; const alice = req.query.user === 'alice'; return { identity: req.query.user, groups: alice ? ['staff'] : [], claims: { role: alice ? 'admin' : 'user' }, request: { country: alice ? 'US' : 'CA' } }; },
      })], controllers: [SignedController],
    }).compile();
    app = mod.createNestApplication(); await app.listen(0, '127.0.0.1');
    const socket = await connection;
    const provider = mod.get(TogglyProvider);
    await eventually(() => assert.equal(provider.state.wsConnected, true));
    const url = await app.getUrl();
    const read = async user => (await fetch(`${url}/evaluate?user=${user}`)).json();
    assert.equal(provider.state.initialized, true);
    assert.equal(provider.state.error, null, 'valid canonical signed startup must not degrade to defaults');
    const [alice, bob] = await Promise.all([read('alice'), read('bob')]);
    assert.deepEqual(alice.flags, [true, true, true, true, true]);
    assert.deepEqual(bob.flags, [false, false, false, false, false]);
    assert.equal(alice.context.identity, 'alice'); assert.equal(bob.context.identity, 'bob'); assert.equal(contextCalls, 2);
    assert.equal((await fetch(`${url}/guarded?user=alice`)).status, 200);
    assert.equal((await fetch(`${url}/guarded?user=bob`)).status, 404);
    // Preserve last-known-good definitions for changed raw bytes, malformed
    // signatures, altered timestamps and a kid not present in the cached JWKS.
    for (const corrupt of [
      { ...fixtures.initial, defs: fixtures.initial.defs.replace('alice', 'bob') },
      { ...fixtures.initial, signature: 'invalid' },
      { ...fixtures.initial, timestamp: fixtures.initial.timestamp + 1 },
      fixtures.rotated,
    ]) {
      state.body = envelope(corrupt); await provider.client.refresh();
      assert(provider.state.error instanceof Error);
      assert.deepEqual((await read('alice')).flags, [true, true, true, true, true]);
    }
    assert.equal(errors.length, 4);
    state.body = envelope(fixtures.rotated); state.jwks = fixtures.rotated.jwks;
    socket.send(JSON.stringify({ type: 'signing-key-updated' }));
    await eventually(async () => {
      assert.equal(provider.state.error, null);
      assert.deepEqual((await read('bob')).flags, [true, false, false, false, false]);
    });
    assert.equal((await read('alice')).flags[0], false);
    assert.equal((await fetch(`${url}/guarded?user=bob`)).status, 200);
    assert.equal((await fetch(`${url}/guarded?user=alice`)).status, 404);
    assert.equal(state.jwksRequests, 2, 'key rotation refetches JWKS');
  } finally {
    if (app) await app.close();
    for (const socket of wss.clients) socket.terminate();
    await new Promise(resolve => wss.close(resolve));
    await stop(socketServer); await stop(transport);
  }
}
